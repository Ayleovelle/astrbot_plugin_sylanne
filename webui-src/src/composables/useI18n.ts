const dicts: Record<string, Dict> = { zh, en }

export function useI18n() {
  const { lang } = useLang()
  function t(key: string): string {
    const d = dicts[lang.value] || zh
    return d[key] ?? zh[key] ?? key
  }
  return { t, lang }
}
